#!/usr/bin/env python3
"""Rasterises the Tiden logo (SVG path, even-odd) into a pixel mask for the wall clock in room.c.

    python3 tools/logo_clock.py <tiden_logo.svg> <diameter_px>

Prints C rows: 'b' = the logo's filled part (drawn blue), 'g' = the hole inside the disc (drawn green),
'.' = outside. Each pixel takes the majority of 6x6 samples."""
import re
import sys


def subpaths(d):
    toks = re.findall(r"[MCLZmclz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    paths, cur, i, cmd, pos = [], [], 0, None, (0.0, 0.0)
    while i < len(toks):
        t = toks[i]
        if t in "MCLZ":
            cmd = t
            i += 1
            if cmd == "Z":
                paths.append(cur)
                cur = []
            continue
        if cmd == "M":
            pos = (float(toks[i]), float(toks[i + 1]))
            cur = [pos]
            i += 2
            cmd = "L"
        elif cmd == "L":
            pos = (float(toks[i]), float(toks[i + 1]))
            cur.append(pos)
            i += 2
        elif cmd == "C":
            p1 = (float(toks[i]), float(toks[i + 1]))
            p2 = (float(toks[i + 2]), float(toks[i + 3]))
            p3 = (float(toks[i + 4]), float(toks[i + 5]))
            p0 = pos
            for k in range(1, 17):
                s = k / 16
                a, b, c, e = (1 - s) ** 3, 3 * (1 - s) ** 2 * s, 3 * (1 - s) * s * s, s ** 3
                cur.append((a * p0[0] + b * p1[0] + c * p2[0] + e * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + e * p3[1]))
            pos = p3
            i += 6
        else:
            raise ValueError("unsupported path command " + str(cmd))
    if cur:
        paths.append(cur)
    return paths


def inside(poly, x, y):
    c = False
    for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            c = not c
    return c


def main():
    svg = open(sys.argv[1]).read()
    n = int(sys.argv[2])
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    outer, hole = subpaths(re.search(r' d="([^"]+)"', svg).group(1))[:2]
    ss = 6
    print(f"/* Tiden logo, {n}x{n} px: generated by tools/logo_clock.py from tiden_logo.svg */")
    for r in range(n):
        row = ""
        for c in range(n):
            votes = {"b": 0, "g": 0, ".": 0}
            for sy in range(ss):
                for sx in range(ss):
                    x = vb[0] + (c + (sx + 0.5) / ss) / n * vb[2]
                    y = vb[1] + (r + (sy + 0.5) / ss) / n * vb[3]
                    if not inside(outer, x, y):
                        votes["."] += 1
                    elif inside(hole, x, y):
                        votes["g"] += 1
                    else:
                        votes["b"] += 1
            row += max(votes, key=votes.get)
        print(f'    "{row}",')


main()
